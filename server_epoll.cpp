// append to the back
static void buf_append(Buffer &buf, const uint8_t *data, size_t len) {
    buf.insert(buf.end(), data, data + len);
}
// remove from the front
static void buf_consume(Buffer &buf, size_t n) {
    buf.erase(buf.begin(), buf.begin() + n);
}

struct Conn {
    int fd = -1;
    // protocol
    enum Proto { PROTO_BINARY, PROTO_RESP } proto = PROTO_BINARY;

    bool pubsub_mode = false;
    std::unordered_set<std::string> subscriptions;

    // application's intention, for the event loop
    bool want_read = false;
    bool want_write = false;
    bool want_close = false;
    // buffered input and output
    Buffer incoming;    // data to be parsed by the application
    size_t incoming_start = 0;
    Buffer outgoing;    // responses generated by the application
    // timer
    uint64_t last_active_ms = 0;
    DList idle_node;
};

static std::unordered_map<std::string, std::unordered_set<Conn*>>  channels;

static void conn_consume_incoming(Conn* conn, size_t n) {
    conn->incoming_start += n;
    if (conn->incoming_start >= conn->incoming.size()) {
        conn->incoming.clear();
        conn->incoming_start = 0;
    }
    return;
}

