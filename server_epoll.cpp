static void do_request(std::vector<std::string> &cmd, Conn *conn, bool resp = false) {
    if (cmd.empty()) {
        return resp
            ? out_resp_err(conn->outgoing, "empty command")
            : out_err(conn->outgoing, ERR_BAD_ARG, "empty command");
    }

    auto it = k_cmd_map.find(cmd[0]);
    Cmd c = (it != k_cmd_map.end()) ? it->second : Cmd::UNKNOWN;

    switch (c) {
    case Cmd::GET:
        if (cmd.size() != 2) break;
        if (conn->pubsub_mode) return;
        return do_get(cmd, conn->outgoing, resp);
    case Cmd::SET:
        if (cmd.size() != 3) break;
        if (conn->pubsub_mode) return;
        return do_set(cmd, conn->outgoing, resp);
    case Cmd::DEL:
        if (cmd.size() != 2) break;
        if (conn->pubsub_mode) return;
        return do_del(cmd, conn->outgoing, resp);
    case Cmd::PEXPIRE:
        if (cmd.size() != 3) break;
        if (conn->pubsub_mode) return;
        return do_expire(cmd, conn->outgoing, resp);
    case Cmd::PTTL:
        if (cmd.size() != 2) break;
        if (conn->pubsub_mode) return;
        return do_ttl(cmd, conn->outgoing, resp);
    case Cmd::KEYS:
        if (cmd.size() != 1) break;
        if (conn->pubsub_mode) return;
        return do_keys(cmd, conn->outgoing, resp);
    case Cmd::ZADD:
        if (cmd.size() != 4) break;
        if (conn->pubsub_mode) return;
        return do_zadd(cmd, conn->outgoing, resp);
    case Cmd::ZREM:
        if (cmd.size() != 3) break;
        if (conn->pubsub_mode) return;
        return do_zrem(cmd, conn->outgoing, resp);
    case Cmd::ZSCORE:
        if (cmd.size() != 3) break;
        if (conn->pubsub_mode) return;
        return do_zscore(cmd, conn->outgoing, resp);
    case Cmd::ZQUERY:
        if (cmd.size() != 6) break;
        if (conn->pubsub_mode) return;
        return do_zquery(cmd, conn->outgoing, resp);
    case Cmd::SUBSCRIBE:
        if (cmd.size() < 2) break;
        return do_subscribe(conn, cmd, conn->outgoing, resp);
    case Cmd::UNSUBSCRIBE:
        if (cmd.size() < 1) break;
        return do_unsubscribe(conn, cmd, resp);
    case Cmd::PUBLISH:
        if (cmd.size() != 3) break;
        return do_publish(cmd, conn, resp);
    case Cmd::VSET:
        if (cmd.size() != 2) break;
        if (conn->pubsub_mode) return;
        return do_vset(cmd, conn->outgoing, resp);
    case Cmd::VDEL:
        if (cmd.size() != 2) break;
        if (conn->pubsub_mode) return;
        return do_vdel(cmd, conn->outgoing, resp);
    case Cmd::VSEARCH:
        if (cmd.size() < 2 || cmd.size() > 3) break;
        if (conn->pubsub_mode) return;
        return do_vsearch(cmd, conn->outgoing, resp);
    case Cmd::PING:
        if (cmd.size() != 1) break;
        return resp
            ? out_resp_str(conn->outgoing, "PONG")
            : out_str(conn->outgoing, "PONG", 4);
    case Cmd::HELLO:
        out_resp_arr_header(conn->outgoing, 14);
        out_resp_str(conn->outgoing, "server");  out_resp_str(conn->outgoing, "redis");
        out_resp_str(conn->outgoing, "version"); out_resp_str(conn->outgoing, "7.0.0");
        out_resp_str(conn->outgoing, "proto");   out_resp_int(conn->outgoing, 2);
        out_resp_str(conn->outgoing, "id");      out_resp_int(conn->outgoing, conn->fd);
        out_resp_str(conn->outgoing, "mode");    out_resp_str(conn->outgoing, "standalone");
        out_resp_str(conn->outgoing, "role");    out_resp_str(conn->outgoing, "master");
        out_resp_str(conn->outgoing, "modules"); out_resp_arr_header(conn->outgoing, 0);
        return;
    default:
        break;
    }
    return resp
        ? out_resp_err(conn->outgoing, "unknown command")
        : out_err(conn->outgoing, ERR_UNKNOWN, "unknown command");
}

static void response_begin(Buffer &out, size_t *header) {
    *header = out.size();       // messege header position
    buf_append_u32(out, 0);     // reserve space
}
static size_t response_size(Buffer &out, size_t header) {
    return out.size() - header - 4;
}
static void response_end(Buffer &out, size_t header) {
    size_t msg_size = response_size(out, header);
    if (msg_size > k_max_msg) {
        out.resize(header + 4);
        out_err(out, ERR_TOO_BIG, "response is too big.");
        msg_size = response_size(out, header);
    }
    // message header
    uint32_t len = (uint32_t)msg_size;
    memcpy(&out[header], &len, 4);
}

static bool try_one_request_resp(Conn* conn) {
    const uint8_t *data = conn->incoming.data() + conn->incoming_start;
    size_t size = conn->incoming.size() - conn->incoming_start;

    if (size < 4) return false;
    if (data[0] != '*') {
        msg("invalid RESP: expected *");
        conn->want_close = true;
        return false;
    }

    // find end of first line
    const uint8_t *end = (const uint8_t *)memchr(data, '\n', size);
    if (!end) return false;

    int nargs = atoi((char *)data + 1);
    if (nargs <= 0 || nargs > (int)k_max_args) {
        msg("invalid RESP: bad nargs");
        conn->want_close =  true;
        return false;
    }

    std::vector<std::string> cmd;
    cmd.reserve(nargs);
    const uint8_t* cur = end + 1;
    for (int i = 0; i < nargs; i++) {
        if (cur >= data + size || *cur != '$') return false;

        // find end of the length line
        const uint8_t* lend = (const uint8_t *)memchr(cur, '\n', (data + size) - cur);
        if (!lend) return false;

        int len = atoi((char *)cur + 1);
        if (len < 0) {
            msg("invalid RESP: bad bulk length");
            conn->want_close = true;
            return false;
        }
        cur = lend + 1;
        // check we have len bytes + \r\n
        if (cur + len + 2 > data + size) return false;

        cmd.push_back(std::string((char *)cur, len));
        cur += len + 2;  // skip data and \r\n
    }
    for (auto &c : cmd[0]) c = tolower(c);

    do_request(cmd, conn, true);
    conn_consume_incoming(conn, cur - data);
    return true;
}

// process 1 request if there is enough data
static bool try_one_request(Conn* conn) {
    // try to parse the protocol: message header
    uint8_t* data = conn->incoming.data() + conn->incoming_start;
    size_t size = conn->incoming.size() - conn->incoming_start;

    if (size < 4) {
        return false;   // want read
    }
    uint32_t len = 0;
    memcpy(&len, data, 4);
    if (len > k_max_msg) {
        msg("too long");
        conn->want_close = true;
        return false;   // want close
    }
    // message body
    if (4 + len > size){
        return false;   // want read
    }
     const uint8_t* request = data + 4;

    // got one request, do some application logic
    std::vector<std::string> cmd;
    if (parse_req(request, len, cmd) < 0) {
        msg("bad request");
        conn->want_close = true;
        return false;   // want close
    }
    size_t header_pos = 0;
    response_begin(conn->outgoing, &header_pos);
    do_request(cmd, conn);
    response_end(conn->outgoing, header_pos);

    // application logic done! remove the request message.
    conn_consume_incoming(conn, 4 + len);
    
    return true;        // success
}

// application callback when the socket is writable
static void handle_write(int epfd, Conn *conn) {
    assert(conn->outgoing.size() > 0);
    ssize_t rv = write(conn->fd, &conn->outgoing[0], conn->outgoing.size());
    if (rv < 0 && errno == EAGAIN) {
        return; // actually not ready
    }
    if (rv < 0) {
        msg_errno("write() error");
        conn->want_close = true;    // error handling
        return;
    }

    // remove written data from `outgoing`
    buf_consume(conn->outgoing, (size_t)rv);

    // update the readiness intention
    if (conn->outgoing.size() == 0) {   // all data written
        conn->want_read = true;
        conn->want_write = false;
        conn_update_events(epfd, conn);
    } // else: want write
}

// application callback when the socket is readable
static void handle_read(int epfd, Conn *conn) {
    // read some data
    uint8_t buf[64 * 1024];
    ssize_t rv = read(conn->fd, buf, sizeof(buf));
    if (rv < 0 && errno == EAGAIN) {
        return; // actually not ready
    }
    // handle IO error
    if (rv < 0) {
        msg_errno("read() error");
        conn->want_close = true;
        return; // want close
    }
    // handle EOF
    if (rv == 0) {
        if (conn->incoming.size() == 0) {
            msg("client closed");
        } else {
            msg("unexpected EOF");
        }
        conn->want_close = true;
        return; // want close
    }
    // got some new data
    buf_append(conn->incoming, buf, (size_t)rv);

    // parse requests and generate responses
    if (conn->proto == Conn::PROTO_RESP) {
        while (try_one_request_resp(conn)) {}
    } else {
        while (try_one_request(conn)) {}
    }
    
    

    // update the readiness intention
    if (conn->outgoing.size() > 0) {    // has a response
        conn->want_read = false;
        conn->want_write = true;
        conn_update_events(epfd, conn);
        // The socket is likely ready to write in a request-response protocol,
        // try to write it without waiting for the next iteration.
        return handle_write(epfd, conn);
    }   // else: want read
}

static void conn_update_events(int epfd, Conn *conn) {
    epoll_event ev{};
    if (conn->want_read) {
        ev.events |=  EPOLLIN;
    }
    if (conn->want_write) {
        ev.events |= EPOLLOUT;
    }
    ev.data.ptr = conn;
    if (epoll_ctl(epfd, EPOLL_CTL_MOD, conn->fd, &ev) < 0) {
        msg_errno("epoll_ctl(MOD)");
    }
}



static uint32_t next_timer_ms(uint64_t idle_timeout_ms) {
    uint64_t now_ms = get_monotonic_msec();
    uint64_t next_ms = (uint64_t)-1;
    // idle timers using a linked list
    if (!dlist_empty(&g_data.idle_list)) {
        Conn *conn = container_of(g_data.idle_list.next, Conn, idle_node);
        next_ms = conn->last_active_ms + idle_timeout_ms;
    }
    // TTL timers using a heap
    if (!g_data.heap.empty() && g_data.heap[0].val < next_ms) {
        next_ms = g_data.heap[0].val;
    }
    // timeout value
    if (next_ms == (uint64_t)-1) {
        return -1;  // no timers, no timeouts
    }
    if (next_ms <= now_ms) {
        return 0;   // missed?
    }
    return (int32_t)(next_ms - now_ms);
}

static bool hnode_same(HNode *node, HNode *key) {
    return node == key;
}

static void process_timers(int epfd, uint64_t idle_timeout_ms) {
    uint64_t now_ms = get_monotonic_msec();
    // idle timers using a linked list
    while (!dlist_empty(&g_data.idle_list)) {
        Conn *conn = container_of(g_data.idle_list.next, Conn, idle_node);
        uint64_t next_ms = conn->last_active_ms + idle_timeout_ms;
        if (next_ms >= now_ms) {
            break;  // not expired
        }

        fprintf(stderr, "removing idle connection: %d\n", conn->fd);
        conn_destroy(epfd, conn);
    }
    // TTL timers using a heap
    const size_t k_max_works = 2000;
    size_t nworks = 0;
    const std::vector<HeapItem> &heap = g_data.heap;
    while (!heap.empty() && heap[0].val < now_ms) {
        Entry *ent = container_of(heap[0].ref, Entry, heap_idx);
        HNode *node = hm_delete(&g_data.db, &ent->node, &hnode_same);
        assert(node == &ent->node);
        // fprintf(stderr, "key expired: %s\n", ent->key.c_str());
        // delete the key
        entry_del(ent);
        if (nworks++ >= k_max_works) {
            // don't stall the server if too many keys are expiring at once
            break;
        }
    }
}

